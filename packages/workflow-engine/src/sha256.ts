/**
 * SHA-256, implemented in plain TypeScript.
 *
 * The definition hash has to be identical in the browser (the editor computes it
 * to detect unsaved changes) and on the server (which stores it), and it has to be
 * synchronous. `node:crypto` cannot be bundled for the browser and Web Crypto is
 * async, so the algorithm lives here and the whole workflow-engine package stays
 * isomorphic. Verified against known test vectors in sha256.test.ts.
 */

